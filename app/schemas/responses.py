"""Response contracts. Pydantic models are the single source of truth for JSON Schema."""

from datetime import datetime
from enum import StrEnum
from typing import Literal, Self

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.schemas.errors import ErrorDetail, RetryMetadata


class ResponseStatus(StrEnum):
    SUCCESS = "success"
    NEEDS_CLARIFICATION = "needs_clarification"
    ERROR = "error"


class Intent(StrEnum):
    CODING_QUESTION = "coding_question"
    DEBUGGING = "debugging"
    CODE_EXPLANATION = "code_explanation"
    LEARNING = "learning"
    CODE_GENERATION = "code_generation"
    CODE_REVIEW = "code_review"
    GENERAL = "general"


class CodeBlock(BaseModel):
    model_config = ConfigDict(extra="forbid")

    language: str = Field(min_length=1, max_length=40, description="e.g. python, typescript, sql")
    code: str = Field(min_length=1, max_length=20000)
    explanation: str | None = Field(default=None, max_length=2000)


class Source(BaseModel):
    """A reference. Only user-supplied sources are ever returned by the application."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(min_length=1, max_length=300)
    url: str | None = Field(default=None, max_length=2000)


class AssistantResponse(BaseModel):
    """The central contract every successful assistant reply must satisfy."""

    model_config = ConfigDict(extra="forbid")

    status: ResponseStatus
    intent: Intent
    answer: str = Field(min_length=1, max_length=20000, description="The main response.")
    summary: str | None = Field(default=None, max_length=500)
    code_blocks: list[CodeBlock] = Field(default_factory=list, max_length=20)
    steps: list[str] = Field(default_factory=list, max_length=30)
    concepts: list[str] = Field(default_factory=list, max_length=30)
    assumptions: list[str] = Field(default_factory=list, max_length=20)
    follow_up_questions: list[str] = Field(default_factory=list, max_length=10)
    sources: list[Source] = Field(default_factory=list, max_length=20)
    error: ErrorDetail | None = None

    @model_validator(mode="after")
    def _check_status_consistency(self) -> Self:
        if self.status is ResponseStatus.NEEDS_CLARIFICATION and not self.follow_up_questions:
            raise ValueError("status 'needs_clarification' requires follow_up_questions")
        if self.status is ResponseStatus.ERROR and self.error is None:
            raise ValueError("status 'error' requires an error object")
        return self


class Exercise(BaseModel):
    model_config = ConfigDict(extra="forbid")

    prompt: str = Field(min_length=1, max_length=2000)
    hint: str | None = Field(default=None, max_length=1000)
    solution: str | None = Field(default=None, max_length=5000)


class QuizQuestion(BaseModel):
    model_config = ConfigDict(extra="forbid")

    question: str = Field(min_length=1, max_length=1000)
    options: list[str] = Field(default_factory=list, max_length=8)
    answer: str = Field(min_length=1, max_length=1000)
    explanation: str | None = Field(default=None, max_length=1000)


class LearningResponse(AssistantResponse):
    """AssistantResponse plus learning-specific sections."""

    exercises: list[Exercise] = Field(default_factory=list, max_length=10)
    quiz: list[QuizQuestion] = Field(default_factory=list, max_length=15)
    common_mistakes: list[str] = Field(default_factory=list, max_length=15)
    project_ideas: list[str] = Field(default_factory=list, max_length=10)
    learning_summary: str | None = Field(default=None, max_length=1500)


AI_NOTICE = (
    "AI-generated by a local model. Schema-valid, but not independently verified: "
    "run and review any code, exercises and answers before relying on them."
)


class AssistantResult(BaseModel):
    """What the API returns on success: a validated response plus run metadata."""

    request_id: str
    mode: str
    model: str
    response: AssistantResponse
    schema_valid: Literal[True] = True
    ai_generated: Literal[True] = True
    verified: Literal[False] = False
    notice: str = AI_NOTICE
    retry: RetryMetadata
    elapsed_ms: int


class LearningResult(AssistantResult):
    response: LearningResponse  # type: ignore[assignment]


class ModelInformation(BaseModel):
    name: str
    size_bytes: int | None = None
    modified_at: datetime | None = None
    family: str | None = None
    parameter_size: str | None = None
    quantization_level: str | None = None


class ModelsResponse(BaseModel):
    models: list[ModelInformation]
    selected_model: str
    selected_model_installed: bool


class HealthResponse(BaseModel):
    status: Literal["ok"] = "ok"
    app: str = "codemind"
    version: str


class OllamaHealthResponse(BaseModel):
    reachable: bool
    base_url: str
    ollama_version: str | None = None
    selected_model: str
    model_installed: bool = False
    structured_output_supported: bool | None = None
    detail: str | None = None
